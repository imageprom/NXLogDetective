def relink(findings):
    for x in findings:
        if x.get('лист') in LINK: x['лист'] = LINK[x['лист']]


def sheets_for(S):
    """Что из расчётов блока пишется в файл: без замещённых листов, с новыми именами."""
    return {RENAME.get(k, k): v for k, v in S.items() if k not in DROP}


def _d(v):
    try: return pd.to_datetime(v).strftime('%d.%m.%Y')
    except Exception: return str(v or '')


def _t(v):
    try: return pd.to_datetime(v).strftime('%d.%m.%Y %H:%M')
    except Exception: return str(v or '')


def code_tab(wb, T, family):
    """Вкладка по коду: каждый адрес с этим кодом — кто получил, откуда пришёл; сканеры видны серыми строками."""
    D = by_family(T, family)
    if not len(D): return None
    D = D.head(5000)
    d = pd.DataFrame({'Адрес': D['адрес'], 'Раздел': D['раздел'], 'Форма': D['форма'], 'Существование': D['существование'],
                      'Коды': D['коды'], 'Запросов': D['запросов'].astype(int), **{nm: D[nm].astype(int) for nm in WHO},
                      'IP': D['IP'].astype(int), **{nm: D[nm].astype(int) for nm in ORIGIN}, 'Пример источника': D['источник'],
                      'Первый': D['первый'].map(_d), 'Последний': D['последний'].map(_d)})
    if family != '5xx' and family != '403 и прочие 4xx': d = d.drop(columns='Коды')
    alien = list(D['чужое'])
    sub = {'404': 'Все адреса, на которые сервер ответил «не найдено»',
           '5xx': 'Все адреса, на которых сервер ответил ошибкой',
           '403 и прочие 4xx': 'Запрещено, неверный запрос и другие отказы, кроме 404',
           '499': 'Посетитель ушёл, не дождавшись ответа: признак медленной страницы'}[family]
    kpi = [('Адресов', len(D)), ('Запросов', int(D['запросов'].sum())), ('У людей', int(D['Люди'].sum())), ('Сканеры и чужое', int(sum(alien)))]
    widths = {'Адрес': 50, 'Раздел': 18, 'Форма': 10, 'Существование': 13, 'Коды': 18, 'Запросов': 10, 'IP': 8, 'Пример источника': 30, 'Первый': 11, 'Последний': 11,
              **{nm: 10 for nm in WHO}, **{nm: 11 for nm in ORIGIN}}
    data_sheet(wb, family, d, family, sub, widths, wrap=('Адрес', 'Пример источника', 'Коды'), center=('Форма', 'Существование'),
               kpi=kpi, kpi_col='Запросов', row_rule=lambda r, _it=iter(alien): F_GREY if next(_it) else None, red=('Коды',),
               links=[('Сводка ошибок', 'Обзор'), ('Ошибки по дням', 'Журнал ошибок')])
    ws = wb[family]
    r_ = ws.max_row + 2
    for t_ in ['Серым — зонды сканеров и битые адреса посторонних: это не ошибки сайта, но видно, что и откуда просили.',
               'Существование — по ответам людям и своим за весь период: живой (хоть раз 2xx), переадресация, сломан (5xx), не существует.',
               'Откуда: со страниц сайта — по ссылке или из кода страницы; напрямую — без перехода; с других сайтов — по ссылке извне.'
               + (' Показаны первые 5 000 адресов.' if len(by_family(T, family)) > 5000 else '')]:
        c_ = ws.cell(r_, 2, t_); c_.font = Font(name='Arial', size=9, italic=True, color=GREY); r_ += 1
    return ws


