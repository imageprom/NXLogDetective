def overview(wb, res, S, site):
    """Первый лист файла: шапка с логотипом и сводка ошибок блоками, у каждого — подпись и ссылка на полный лист."""
    E = res.get('errors') or {}
    sm = E.get('сводка') or {}
    if 'Обзор' in wb.sheetnames: del wb['Обзор']
    ws = wb.create_sheet('Обзор', 0)
    W = Wide(ws)
    brand_header(ws, W, res, f'NX LOG DETECTIVE — ОШИБКИ САЙТА {site.upper()}', 'Что сломано на сайте, кто на это наткнулся и где это править', last='I')
    names = set(wb.sheetnames)
    K = sm.get('коды')
    if K is not None and len(K):
        W.section('Ответы сервера', 'Все ответы за период — по тем, кто их получил. 499 — посетитель ушёл, не дождавшись ответа: это не ошибка, а признак медленной страницы.')
        rows = [[r['кто'], int(r['запросов']), int(r['ок']), int(r['e4']), int(r['e5']), int(r['n499']),
                 f"{(r['e4'] + r['e5']) / max(1, r['запросов']) * 100:.1f}%".replace('.', ',')] for _, r in K.iterrows()]
        W.table(['Кто', 'Запросов', 'Без ошибок', 'Ошибки 4xx', 'Ошибки 5xx', '499 — не дождались', 'Доля ошибок'], rows, ['B', 'C', 'D', 'E', 'F', 'G', 'HI'], num=(1, 2, 3, 4, 5, 6))
        W.link('Ошибки по дням', 'Журнал ошибок', names)
    X = S.get('Сбои')
    if X is not None and len(X):
        W.section('Сбои', 'Окна, когда сервер отвечал ошибками на многие страницы сразу. Статика при этом обычно отдаётся — падает динамика.')
        rows = [[_t(r['начало']), _t(r['конец']), int(r['минут_всего']), int(r['страниц_с_5xx']), int(r['обрывов_499']), str(r.get('вероятная_причина', '')).split(';')[0]] for _, r in X.iterrows()]
        W.table(['Начало', 'Конец', 'Минут', 'Страниц с 5xx', 'Обрывов 499', 'Вероятная причина'], rows, ['B', 'C', 'D', 'E', 'F', 'GHI'], num=(2, 3, 4))
        W.link('Все сбои', 'Сбои', names)
    P = sm.get('страницы')
    if P is not None and len(P):
        W.section('Сломано у людей', 'Топ-10 страниц сайта, на которых люди получили ошибку. Откуда — страница сайта или сайт, с которого пришли.')
        rows = [[r['адрес'], r['коды'], int(r['Люди']), int(r['Поисковики']), r['существование'], r['источник']] for _, r in P.iterrows()]
        W.table(['Страница', 'Коды', 'Люди', 'Поисковики', 'Существование', 'Откуда'], rows, ['BC', 'D', 'E', 'F', 'G', 'HI'], num=(2, 3), center=(1, 4))
        W.link('Все адреса с 404', '404', names); W.link('Все адреса с 5xx', '5xx', names)
    G = sm.get('разделы')
    if G is not None and len(G):
        W.section('Ошибки по разделам', 'Где на сайте больше всего ошибок у людей, своих и поисковиков. Зонды сканеров не учитываются.')
        rows = [[r['раздел'], int(r['адресов']), int(r['Люди']), int(r['Поисковики']), int(r['Свои'])] for _, r in G.head(10).iterrows()]
        W.table(['Раздел', 'Адресов', 'Люди', 'Поисковики', 'Свои'], rows, ['BC', 'D', 'E', 'F', 'G'], num=(1, 2, 3, 4))
    Fg = sm.get('файлы')
    if Fg is not None and len(Fg):
        W.section('Файлы с ошибками', 'Картинки, шрифты, стили и другие файлы, которые сервер не отдал. Больше всего бьёт по людям то, что подгружают сами страницы сайта.')
        rows = [[r['группа'], int(r['файлов']), int(r['Люди']), '\n'.join(r['примеры'])] for _, r in Fg.iterrows()]
        W.table(['Группа', 'Файлов', 'Ошибок у людей', 'Например'], rows, ['B', 'C', 'D', 'EFGHI'], num=(1, 2), wrap=0.95)
        W.link('Каждый файл', 'Файлы с ошибками', names)
    BL = S.get('Битые ссылки')
    if BL is not None and len(BL):
        W.section('Битые ссылки', 'Ссылки внутри сайта, которые ведут на несуществующие страницы.')
        rows = [[r['куда (шаблон)'], int(r['переходов']), int(r['визитов']), str(r['главный_источник']).split(': ')[0]] for _, r in BL.head(5).iterrows()]
        W.table(['Куда ведёт', 'Переходов', 'Визиты', 'Где стоит ссылка'], rows, ['BC', 'D', 'E', 'FGHI'], num=(1, 2))
        W.link('Все битые ссылки', 'Битые ссылки', names)
    BJ = S.get('Битые адреса из скриптов')
    if BJ is not None and len(BJ):
        W.section('Битые адреса из скриптов', 'Скрипты страниц подставляют в адрес переменную, которой нет: браузер запрашивает несуществующий адрес.')
        rows = [[r['Адрес'], int(r['Запросов со страниц сайта']), r['Страница-источник']] for _, r in BJ.head(5).iterrows()]
        W.table(['Адрес', 'Запросов', 'Страница'], rows, ['BCD', 'E', 'FGHI'], num=(1,))
        W.link('Все битые адреса', 'Битые адреса из скриптов', names)
    SE = S.get('Ошибки у поисковиков')
    if SE is not None and len(SE):
        W.section('Ошибки у поисковиков', 'Страницы, которые поисковые роботы получают с ошибкой: такие адреса выпадают из поиска.')
        g = SE.groupby('робот').agg(типов=('шаблон', 'nunique'), запросов=('запросов', 'sum'), ошибок=('ошибок', 'sum')).sort_values('ошибок', ascending=False).reset_index()
        W.table(['Робот', 'Типов страниц', 'Запросов', 'Ошибок'], [[r['робот'], int(r['типов']), int(r['запросов']), int(r['ошибок'])] for _, r in g.iterrows()], ['B', 'C', 'D', 'E'], num=(1, 2, 3))
        W.link('Какие страницы', 'Ошибки у поисковиков', names)
    AD = S.get('Реклама: посадочные с ошибками')
    if AD is not None and len(AD):
        W.section('Реклама на ошибки', 'Рекламные клики, которые привели на страницу с ошибкой или на страницу, которую человек не дождался.')
        rows = [[r['entry'], int(r['entry_status']), int(r['кликов'])] for _, r in AD.head(5).iterrows()]
        W.table(['Посадочная', 'Код', 'Кликов'], rows, ['BCD', 'E', 'F'], num=(2,), center=(1,))
        W.link('Все посадочные', 'Реклама на ошибки', names)
    EL = S.get('Error-лог')
    if EL is not None and len(EL):
        W.section('Error-лог', 'Что сервер записал в журнал ошибок, по типам.')
        rows = [[r['тип'], int(r['сообщений']), _d(r['первый']), _d(r['последний'])] for _, r in EL.iterrows()]
        W.table(['Тип', 'Сообщений', 'Первый', 'Последний'], rows, ['BC', 'D', 'E', 'F'], num=(1,), center=(2, 3))
        W.link('Примеры сообщений', 'Error-лог', names)
    ws.page_setup.orientation = 'portrait'; ws.page_setup.fitToWidth = 1; ws.page_setup.fitToHeight = 0
    ws.sheet_properties.pageSetUpPr.fitToPage = True
    return ws


def build(wb, res, S, site):
    E = res.get('errors') or {}
    T = E.get('коды')
    if 'Журнал ошибок' not in wb.sheetnames: wb.create_sheet('Журнал ошибок')
    def kpi(body):
        h = body['5xx|Люди'] + body['4xx|Люди']
        return [('Ошибок у людей в день', int(round(h[body['_полный']].mean())) if body['_полный'].any() else int(round(h.mean()))),
                ('Больше всего', _day(body.loc[h.idxmax(), 'день']) if len(body) else ''), ('5xx у людей', int(body['5xx|Люди'].sum()))]
    journal_sheet(wb, 'Журнал ошибок', E.get('журнал'), 'Ошибки 5xx и 4xx и обрывы 499 по дням и по тем, кто их получил', kpi,
                  [('Сводка ошибок', 'Обзор'), ('Все адреса с 404', '404')],
                  ['4xx — без 499: он показан отдельно, это посетитель, который не дождался ответа. Поисковики — только подлинные роботы поисковых систем.',
                   'Время — какая часть суток попала в лог; неполные дни — серым курсивом, в среднее не входят. Выходные — на сером.'], kpi_col='4xx|Люди')
    for fam, _ in FAMILIES:
        if fam not in wb.sheetnames: wb.create_sheet(fam)
        if code_tab(wb, T, fam) is None: del wb[fam]
    if res.get('files_errors'):
        service_files(wb, dict(res, files=res['files_errors']), 'Файлы с ошибками', title='Файлы с ошибками',
                      note='Файлы, на которые сервер хоть раз ответил ошибкой: тот же расчёт, что «Файлы» в Overview',
                      links=[('Сводка ошибок', 'Обзор'), ('Все адреса с 404', '404')], errors_mode=True)
    full_sheets(wb, S)
    overview(wb, res, S, site)
    byname = {w.title: w for w in wb._sheets}
    head_ = [byname[n_] for n_ in ORDER if n_ in byname]
