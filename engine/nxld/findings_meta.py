def ftype(x):
    return x['key'].split(':')[1]


def meta(x):
    return META.get(ftype(x), ('', ''))


def _t(ts):
    return pd.Timestamp(int(ts), unit='s').strftime('%d.%m %H:%M')


def proofs(c, items, sheets):
    """Пример-доказательство для каждой проблемы, где его можно достать из данных. Пишет в x['доказательство']."""
    R, V = c.R, c.V
    human = c.human
    st = R['status'].values
    C = sheets.get('Общий анализ', {}).get('Конверсии', pd.DataFrame())

    def req(mask, n=1):
        idx = np.flatnonzero(mask)
        return R.iloc[idx[:n]] if len(idx) else None

    for x in items:
        t, obj = ftype(x), x['key'].split(':', 2)[2] if x['key'].count(':') >= 2 else ''
        p = ''
        try:
            if t in ('bot_leads', 'operator') and len(C):
                b = C[(C['группа'] == 'Боты') & (C['принята'] == 'да')].sort_values('время')
                if t == 'operator' and obj and obj in set(V['entry']):
                    ips = set(V.loc[V['entry'] == obj, 'ip'])
                    b = b[b['ip'].isin(ips)] if len(b[b['ip'].isin(ips)]) else b
                if len(b):
                    r = b.iloc[0]
                    p = f"{r['ip']}, {str(r['время'])[:16]}: вход на {r['вход']}, через {int(r['сек_от_входа'])} с отправка {r['цель']} — сервер принял"
            elif t in ('outage', 'degradation') and c.E is not None and len(c.E):
                a = pd.Timestamp(obj).timestamp()
                e = c.E[(c.E['ts'] >= a) & (c.E['ts'] <= a + 3600)]
                e = e[e['msg'].astype(str).str.contains('timed out|failed|refused', regex=True)]
                if len(e):
                    r = e.iloc[0]
                    p = f"error-лог, {_t(r['ts'])}: «{str(r['msg'])[:140]}»"
            elif t in ('5xx', '5xx_section'):
                tpl = obj if t == '5xx' else None
                cats = R['tpl'].cat.categories if hasattr(R['tpl'], 'cat') else None
                if t == '5xx' and cats is not None and tpl in set(cats):
                    m = (R['tpl'].values == tpl) & (st >= 500) & human
                else:
                    m = R['base'].astype(str).str.startswith(obj).values & (st >= 500) & human if obj else None
                r = req(m) if m is not None else None
                if r is not None:
                    r = r.iloc[0]; p = f"{_t(r['ts'])}: {r['base']} → {int(r['status'])} (посетитель {r['ip']})"
            elif t == '404_entry':
                v = V[(V['group'] == 'Люди') & (V['entry_status'] == 404) & (V['channel'] == obj)].sort_values('start', ascending=False)
                if len(v):
                    r = v.iloc[0]; p = f"{_t(r['start'])}: вход на {r['entry']} → 404" + (f", пришёл с {r['entry_ref_host']}" if str(r.get('entry_ref_host', '')) not in ('', '-', 'nan') else '')
            elif t in ('service_err', 'no_service', 'exposed', 'missing_static'):
                key = obj.replace('*', '') if obj not in ('files', 'list', 'all', 'site') else ''
                if key:
                    m = R['base'].astype(str).str.startswith(key).values.copy()
                    if t == 'service_err': m = m & (st >= 400)
                    if t in ('missing_static', 'no_service'): m = m & (st == 404)
                    if t == 'open_section': m = m & (st == 200)
                    r = req(m)
                    if r is not None:
                        r = r.iloc[0]
                        p = f"{_t(r['ts'])}: {r['base']} → {int(r['status'])}, запросил {r['fam'] if str(r['fam']) not in ('', 'nan') else r['ip']}"
            elif t == 'ad_landing_errors':
                a = V[(V['channel'] == 'Реклама') & (V['entry_status'] >= 400)].sort_values('start', ascending=False)
                if len(a):
                    r = a.iloc[0]; p = f"{_t(r['start'])}: клик по рекламе → {r['entry']} → {int(r['entry_status'])}"
            elif t == 'fake_crawlers':
                f = sheets.get('Боты', {}).get('Подделки', pd.DataFrame())
                if len(f):
                    r = f.iloc[0]; p = f"{r['ip']} представлялся {r['представлялся']}, сеть {r.get('org') or r.get('сеть')} ({r['страна']}), {int(r['запросов'])} запросов"
            elif t == 'attack_500':
                a = sheets.get('Нагрузка и безопасность', {}).get('Атаки в параметрах', pd.DataFrame())
                a = a[a['status'] >= 500] if len(a) else a
                if len(a):
                    r = a.iloc[0]; p = f"{r['base']}?{str(r['пример'])[:100]} → {int(r['status'])}"
            elif t == 'heavy_images':
                h = sheets.get('Нагрузка и безопасность', {}).get('Тяжёлые файлы', pd.DataFrame())
                if len(h):
                    r = h.iloc[0]; p = f"{r['файл']}: {int(r['средний_КБ'])} КБ, запрошен {int(r['запросов'])} раз"
            if not p:
                p = sheet_proof(t, obj, x, sheets)
        except Exception:
            p = ''
        if p: x['доказательство'] = p
    return items


def sheet_proof(t, obj, x, sheets):
    """Пример из уже посчитанных листов (дёшево и без перебора 10 млн строк)."""
    sh = lambda b, k: sheets.get(b, {}).get(k, pd.DataFrame())
    if t == 'hotlink':
        f = sh('Нагрузка и безопасность', 'Хотлинк')
        if len(f):
            r = f.iloc[0]; return f"{r['ref_host']}: {int(r['запросов'])} запросов картинок, {r['байт'] / 1024 ** 2:.0f} МБ"
    if t == 'broken_labels':
        f = sh('Маркетинг', 'Метки: проблемы')
        if len(f):
            r = f.iloc[0]; return f"{r['проблема']}: {str(r['пример'])[:160]}"
    if t == 'search_errors':
        f = sh('Ошибки', 'Ошибки у поисковиков')
        if len(f):
            r = f.iloc[0]; return f"{r['робот']} запросил {r['шаблон']} {int(r['запросов'])} раз, ошибок {int(r['ошибок'])} ({r.get('коды', '')})"
    if t == 'broken_links':
        b = sh('Ошибки', 'Битые ссылки')
        if len(b):
            r = b.iloc[0]; cols = list(b.columns)
            return '; '.join(f'{c}: {r[c]}' for c in cols[:4])
    if t == 'blocked_people':
        b = sh('Ошибки', 'Защита: кого блокирует')
        b = b[b['кто'] == 'люди'] if len(b) else b
        if len(b):
            r = b.iloc[0]; return f"{r['ответов']} ответов {r['status']} людям из сети «{r['nettype']}» ({r['cc']}), например на {r['пример']}"
    if t == 'errlog':
        e = sh('Ошибки', 'Error-лог'); e = e[e['тип'] == obj] if len(e) else e
        if len(e): return f"«{str(e.iloc[0]['пример'])[:180]}»"
    if t == 'heavy_robot':
        f = sh('Боты', 'Роботы: семейства'); f = f[f['семейство'] == obj] if len(f) else f
        if len(f):
            r = f.iloc[0]; return f"{r['IP']} адресов, {r['дней']} дн.; {int(r['404'])} ответов «не найдено»; смотрел: {r['что_смотрел']}"
    if t == 'placements_off':
        f = sh('Маркетинг', 'Площадки к отключению')
        if len(f):
            r = f.iloc[0]; return f"{r['source']} ({r['тип']}): {r['почему']}"
    if t == 'missing_static':
        f = sh('Ошибки', 'Отсутствующие ресурсы')
        if len(f):
            r = f.iloc[0]; return f"{r['файл']} — {int(r['запросов'])} запросов с {int(r['страниц'])} страниц, ответ 404"
    if t == 'trap':
        f = sh('Нагрузка и безопасность', 'Ловушки для роботов')
        if len(f):
            r = f.iloc[0]; return f"{r['шаблон']} — {int(r['разных_параметров'])} разных вариантов параметров у роботов"
    if t == 'unknown_robot':
        f = sh('Боты', 'Роботы: семейства'); f = f[f['категория'].astype(str).str.contains('Мониторинг')] if len(f) else f
        if len(f):
            r = f.iloc[0]; return f"{r['семейство']}: {int(r['запросов'])} запросов с {r['IP']} адресов за {r['дней']} дн.; смотрит: {r['что_смотрел']}"
    if t == 'placement_type_low':
        f = sh('Маркетинг', 'Реклама: Площадки')
        if len(f) and 'тип' in f:
            f = f[f['тип'].astype(str).str.startswith('РСЯ')].sort_values('визитов', ascending=False)
            if len(f):
                r = f.iloc[0]; return f"{r['source']} ({r['тип']}): {int(r['визитов'])} визитов, заявок {int(r['принято'])}, уход сразу {r['мгновенный_уход_%']}%"
    if t == 'campaign_zero':
        f = sh('Маркетинг', 'Реклама: Кампании'); f = f[f['принято'] == 0].sort_values('визитов', ascending=False) if len(f) else f
        if len(f):
            r = f.iloc[0]; return f"{r['кампания']}: {int(r['визитов'])} визитов, уход сразу {r['мгновенный_уход_%']}%, каталог смотрели {r['смотрели_каталог_%']}%"
    if t == '5xx' and obj in ('группа', 'мелочи'):
        f = sh('Ошибки', '5xx по шаблонам'); f = f[f['у_людей'] < 20] if len(f) else f
        if len(f):
            r = f.iloc[0]; return f"{r['пример']}: {int(r['у_людей'])} ошибок у людей, {r['первый_день']} — {r['последний_день']}"
    if t == '404_entry' and obj in ('группа', 'мелочи'):
        f = sh('Ошибки', '404: входы извне'); f = f[f['канал'].isin(['Карты', 'Поиск'])] if len(f) else f
        if len(f):
            r = f.iloc[0]; return f"{r['адрес']} — {int(r['визитов'])} визитов из канала «{r['канал']}», реферер: {r['реферер']}"
    return ''
