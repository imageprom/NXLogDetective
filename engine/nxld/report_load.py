def build(wb, res, S, site):
    for k_ in ('Сводка', 'О данных'):
        if k_ in wb.sheetnames: del wb[k_]
    build_sheets(wb, res, S)
    if 'GET' in wb.sheetnames:   # персональные данные в адресе (GET) — пока прежний лист, в общем стиле
        G = S.get('GET-отправки')
        if G is not None and len(G):
            data_sheet(wb, 'GET', G.rename(columns={'время': 'Время', 'ip': 'IP', 'адрес': 'Адрес', 'запрос': 'Запрос', 'код': 'Код', 'робот': 'Робот'}), 'GET',
                       'Персональные данные, которые ушли в адресе страницы (GET)', {'Адрес': 40, 'Запрос': 60}, wrap=('Адрес', 'Запрос'), red=())
    overview(wb, res, site)
    byname = {w.title: w for w in wb._sheets}
    head_ = [byname[n_] for n_ in ORDER if n_ in byname]
    wb._sheets = head_ + [w for w in wb._sheets if w not in head_]


