def relink(findings):
    for x in findings:
        if x.get('лист') in LINK: x['лист'] = LINK[x['лист']]


def sheets_for(S):
    """Что из расчётов блока пишется в файл: без замещённых листов, с новыми именами."""
    return {RENAME.get(k, k): v for k, v in S.items() if k not in DROP}


def _d(v):
    try: return pd.to_datetime(v).strftime('%d.%m.%Y')
    except Exception: return str(v or '')


def _t(v):
    try: return pd.to_datetime(v).strftime('%d.%m.%Y %H:%M')
    except Exception: return str(v or '')


def notes(ws, lines):
    r_ = ws.max_row + 2
    for t_ in lines:
        c_ = ws.cell(r_, 2, t_); c_.font = Font(name='Arial', size=9, italic=True, color=GREY); r_ += 1


def code_tab(wb, T, Sr, family):
    """Вкладка по коду: каждый адрес с этим кодом — кто получил, статус, откуда пришли. Сканеры — серым, пострадавшее — персиковым."""
    D_all = by_family(T, family, Sr)
    if not len(D_all): return None
    D = D_all.head(5000)
    d = pd.DataFrame({'Адрес': D['адрес'], 'Запросов': D['запросов'].astype(int), **{nm: D[nm].astype(int) for nm in WHO}, 'IP': D['IP'].astype(int),
                      'Тип': D['тип'], 'Статус': D['статус'], 'Коды': D['коды'], 'Раздел': D['раздел'], 'Источники': D.get('источники', ''),
                      'Первый': D['первый'].map(_d), 'Последний': D['последний'].map(_d)})
    if family in ('404', '499'): d = d.drop(columns='Коды')
    fill = [F_GREY if a else (None if it in ('работает', 'переадресация') else F_NOTE) for a, it in zip(D['чужое'], D['итог'])]
    sub = {'404': 'Адреса, которых нет на сервере: кто их запрашивал и откуда пришёл',
           '5xx': 'Адреса, на которых сервер не смог ответить',
           '403 и прочие 4xx': 'Адреса, на которые сервер ответил отказом: доступ запрещён, неверный запрос и другие, кроме 404',
           '499': 'Адреса, с которых посетители ушли, не дождавшись ответа: признак медленной страницы'}[family]
    kpi = [('Адресов', len(D_all)), ('Запросов', int(D_all['запросов'].sum())), ('У людей', int(D_all['Люди'].sum())), ('Сканеры и чужое', int(D_all['чужое'].sum()))]
    widths = {'Адрес': 48, 'Запросов': 10, 'IP': 8, 'Тип': 11, 'Статус': 34, 'Коды': 18, 'Раздел': 18, 'Источники': 46, 'Первый': 11, 'Последний': 11, **{nm: 10 for nm in WHO}}
    data_sheet(wb, family, d, family, sub, widths, wrap=('Адрес', 'Статус', 'Источники', 'Коды'), center=('Тип',),
               kpi=kpi, kpi_col='Мониторинг', row_rule=lambda r, _it=iter(fill): next(_it), red=('Коды',),
               links=[('Сводка ошибок', 'Обзор'), ('Пострадавшие страницы', 'Пострадавшие страницы')])
    notes(wb[family], ['Белым — адрес работает (ошибка была разовой); персиковым — не работает или работал с перебоями; серым — зонды сканеров и битые адреса посторонних.',
                       'Статус — что происходило с адресом по дням: преобладающий ответ людям, своим и поисковикам. Источники — откуда пришли запросы с ошибкой.'
                       + (' Показаны первые 5 000 адресов.' if len(D_all) > 5000 else '')])
    return wb[family]


def victims(wb, E):
    """«Пострадавшие страницы»: все страницы сайта, на которых люди, свои или поисковики получали ошибку, — с историей."""
    N = E.get('нерабочие')
    name = 'Пострадавшие страницы'
    if N is None or not len(N): return None
    if name not in wb.sheetnames: wb.create_sheet(name)
    d = pd.DataFrame({'Страница': N['адрес'], 'Статус': N['статус'], 'Люди': N['Люди'].astype(int), 'Поисковики': N['Поисковики'].astype(int), 'Свои': N['Свои'].astype(int),
                      'Коды': N['коды'], 'Раздел': N['раздел'], 'Источники': N.get('источники', ''), 'Первый': N['первый'].map(_d), 'Последний': N['последний'].map(_d)})
    fixed = list(N['починился'])
    kpi = [('Страниц', len(d)), ('Не работают сейчас', int((~N['починился']).sum())), ('Починились', int(N['починился'].sum()))]
    data_sheet(wb, name, d, name, 'Страницы, которые сломались, починились или не работали с самого начала', {'Страница': 48, 'Статус': 40, 'Коды': 20, 'Раздел': 18, 'Источники': 50},
               wrap=('Страница', 'Статус', 'Источники', 'Коды'), kpi=kpi, kpi_col='Свои', row_rule=lambda r, _it=iter(fixed): None if next(_it) else F_NOTE, red=('Коды',),
               links=[('Все адреса с 404', '404'), ('Все адреса с 5xx', '5xx')])
    notes(wb[name], ['Персиковым — страница так и не заработала; белым — снова работает. Сканеры сюда не входят.',
                     'Статус по дням: работает, переадресация, отказ, нет на сервере, ошибка сервера. «Весь период» — состояние не менялось ни разу.'])
    return wb[name]


