def sheets_for(S):
    """Что пишется в файл из расчётов блока: только листы без своей вёрстки; остальные строит build."""
    return {('GET' if k == 'GET-отправки' else k): v for k, v in S.items() if k in KEEP}


def _d(v):
    try: return pd.to_datetime(v).strftime('%d.%m.%Y')
    except Exception: return str(v or '')


def notes(ws, lines):
    r_ = ws.max_row + 2
    for t_ in lines:
        c_ = ws.cell(r_, 2, t_); c_.font = Font(name='Arial', size=9, italic=True, color=GREY); r_ += 1


def _ok(X, k):
    v = X.get(k)
    return v is not None and (len(v) if not isinstance(v, dict) else True)


def overlap_note(H):
    """Заметка о пересечении нагрузок: часы, где у людей много запросов и у роботов с ботами тоже, и что с обрывами 499."""
    if not H or H.get('_пересечение') is None or not len(H['_пересечение']): return ''
    X = H['_пересечение']
    top = ', '.join(f"{_day(r['d'])} {int(r['h']):02d}:00" for _, r in X.head(3).iterrows())
    b, o = H.get('_499_обычно') or 0, H.get('_499_в_пересечении')
    tail = ''
    if o is not None and b:
        k = o / b
        tail = (f' В эти часы люди уходили, не дождавшись ответа (499), в {k:.1f} раза чаще обычного — сервер не справляется с общей нагрузкой.'.replace('.', ',', 1) if k >= 1.3
                else ' Обрывов 499 у людей в эти часы не больше обычного — сервер справляется.')
    return f'Куда смотреть: часы, где много и людей, и роботов с ботами, — {top}.{tail}'


