def full_sheets(wb, S):
    """Остальные полные листы — в едином табличном стиле, с человеческими колонками, подписями и подсветкой."""
    def put(name, df, note, rename, widths, wrap=(), kpi=None, kpi_col=None, rule=None, links=(), center=()):
        if df is None or not len(df) or name not in wb.sheetnames: return
        d = df.rename(columns=rename)[[v for v in rename.values() if v in df.rename(columns=rename).columns]]
        data_sheet(wb, name, d, name, note, widths, wrap=wrap, kpi=kpi, kpi_col=kpi_col, row_rule=rule, links=links, center=center)
    X = S.get('Сбои')
    if X is not None and len(X):
        X = X.assign(начало=X['начало'].map(_t), конец=X['конец'].map(_t), доля_5xx_у_страниц_в_пик=(X['доля_5xx_у_страниц_в_пик'] * 100).round(0).astype(int))
        put('Сбои', X, 'Периоды, когда сервер отвечал ошибками на многие страницы сразу',
            {'начало': 'Начало', 'конец': 'Конец', 'минут_всего': 'Минут всего', 'пик_минут': 'Минут пика', 'страниц_с_5xx': 'Страниц с 5xx', 'обрывов_499': 'Обрывов 499',
             'доля_5xx_у_страниц_в_пик': 'Доля 5xx в пик, %', 'запросов_в_мин': 'Запросов в минуту', 'обычно_запросов_в_мин': 'Обычно в минуту', 'вероятная_причина': 'Вероятная причина'},
            {'Начало': 16, 'Конец': 16, 'Вероятная причина': 60}, wrap=('Вероятная причина',), kpi=[('Сбоев', len(X)), ('Минут', int(X['минут_всего'].sum()))], kpi_col='Обычно в минуту')
    B = S.get('Битые адреса из скриптов')
    if B is not None and len(B):
        data_sheet(wb, 'Битые из скриптов', B, 'Битые из скриптов', 'Адреса, которые скрипты страниц собрали с ошибкой',
                   {'Адрес': 50, 'Страница-источник': 40}, wrap=('Адрес', 'Страница-источник'), red=('Коды',), row_rule=lambda r: F_NOTE)
        notes(wb['Битые из скриптов'], ['Скрипт подставляет в адрес переменную, которой нет (${marker.image}, \' + href +), и браузер запрашивает несуществующий адрес. Править — в коде указанной страницы.'])
    SE = S.get('Ошибки у поисковиков')
    if SE is not None and len(SE):
        put('Поисковики — ошибки', SE, 'Страницы, которые поисковые роботы получают с ошибкой, — они выпадают из поиска',
            {'робот': 'Робот', 'шаблон': 'Тип страницы', 'запросов': 'Запросов', 'ошибок': 'Ошибок', 'коды': 'Коды'}, {'Тип страницы': 55, 'Коды': 24}, wrap=('Тип страницы',),
            rule=lambda r: F_NOTE if any(t.strip().startswith('5') for t in str(r.get('Коды', '')).split(',')) else None)
        notes(wb['Поисковики — ошибки'], ['Персиковым — сервер отвечает роботу ошибкой 5xx: страница может выпасть из поиска, даже если она существует. 404 — страницы нет, робот её забудет.'])
    A = S.get('Реклама: посадочные с ошибками')
    if A is not None and len(A):
        put('Ошибки с рекламы', A.assign(первый=A['первый'].map(_d), последний=A['последний'].map(_d)), 'Рекламные переходы, которые привели на неработающую страницу',
            {'entry': 'Посадочная', 'entry_status': 'Код', 'кликов': 'Кликов', 'первый': 'Первый', 'последний': 'Последний'}, {'Посадочная': 55}, wrap=('Посадочная',), center=('Код',),
            rule=lambda r: None if r.get('Код') == 499 else F_NOTE)
        notes(wb['Ошибки с рекламы'], ['Персиковым — клик привёл на несуществующую страницу или на ошибку сервера: деньги потрачены впустую. Белым — 499: человек не дождался загрузки, это вопрос скорости страницы.'])
    P = S.get('Пустые страницы')
    if P is not None and len(P):
        cols = {'base': 'Адрес', 'ответов_меньше_300_байт': 'Ответов меньше 300 байт', 'что': 'Что это', 'комментарий': 'Комментарий'}
        norm = list(P['норма']) if 'норма' in P else [False] * len(P)
        put('Пустые ответы', P, 'Страницы, которые сервер отдал почти пустыми; служебные адреса движка, где это норма, отмечены',
            cols, {'Адрес': 50, 'Что это': 30, 'Комментарий': 55}, wrap=('Адрес', 'Что это', 'Комментарий'), rule=lambda r, _it=iter(norm): F_GREY if next(_it) else None)
        notes(wb['Пустые ответы'], ['Серым — служебный адрес движка, для которого пустой ответ — норма (по справочнику движка). Остальное стоит открыть и проверить.'])
    L = S.get('Error-лог')
    if L is not None and len(L):
        L = L.assign(первый=L['первый'].map(_d), последний=L['последний'].map(_d), значит=L['тип'].map(lambda t: ERRLOG_MEANING.get(t, ('', False))[0]))
        norm = [ERRLOG_MEANING.get(t, ('', False))[1] for t in L['тип']]
        put('Error-лог', L, 'Ошибки из журнала сервера: что они значат и какие запросы их вызвали',
            {'тип': 'Тип', 'значит': 'Что значит', 'сообщений': 'Сообщений', 'первый': 'Первый', 'последний': 'Последний', 'запрос': 'Какие запросы вызывали', 'пример': 'Пример сообщения'},
            {'Тип': 26, 'Что значит': 40, 'Какие запросы вызывали': 55, 'Пример сообщения': 55}, wrap=('Тип', 'Что значит', 'Какие запросы вызывали', 'Пример сообщения'),
            rule=lambda r, _it=iter(norm): F_GREY if next(_it) else None)
        notes(wb['Error-лог'], ['Серым — норма или работа защиты сервера. Остальное — задание разработчику: по запросам видно, что именно падает.'])


def overview(wb, res, S, site):
    """Первый лист файла: шапка с логотипом и сводка ошибок блоками, у каждого — подпись и ссылка на полный лист."""
    E = res.get('errors') or {}
    sm = E.get('сводка') or {}
    if 'Обзор' in wb.sheetnames: del wb['Обзор']
    ws = wb.create_sheet('Обзор', 0)
    W = Wide(ws)
    brand_header(ws, W, res, f'NX LOG DETECTIVE — ОШИБКИ САЙТА {site.upper()}', 'Что сломано на сайте, кто на это наткнулся и где это исправить', last='I')
    names = set(wb.sheetnames)
    K = sm.get('коды')
    if K is not None and len(K):
        W.section('Ответы сервера', 'Все ответы за период — по тем, кто их получил. 499 — посетитель ушёл, не дождавшись ответа: это не ошибка, а признак медленной страницы.')
        rows = [[r['кто'], int(r['запросов']), int(r['ок']), int(r['e4']), int(r['e5']), int(r['n499']),
                 f"{(r['e4'] + r['e5']) / max(1, r['запросов']) * 100:.1f}%".replace('.', ',')] for _, r in K.iterrows() if r['запросов']]
        W.table(['Кто', 'Запросов', 'Без ошибок', 'Ошибки 4xx', 'Ошибки 5xx', '499 — не дождались', 'Доля ошибок'], rows, ['B', 'C', 'D', 'E', 'F', 'G', 'HI'], num=(1, 2, 3, 4, 5, 6))
        W.link('Ошибки по дням', 'Статистика', names)
    X = S.get('Сбои')
    if X is not None and len(X):
        W.section('Сбои', 'Периоды, когда сервер отвечал ошибками на многие страницы сразу. Статика при этом обычно отдаётся — падает динамика.')
        rows = [[_t(r['начало']), _t(r['конец']), int(r['минут_всего']), int(r['страниц_с_5xx']), int(r['обрывов_499']), str(r.get('вероятная_причина', '')).split(';')[0]] for _, r in X.iterrows()]
        W.table(['Начало', 'Конец', 'Минут', 'Страниц с 5xx', 'Обрывов 499', 'Вероятная причина'], rows, ['B', 'C', 'D', 'E', 'F', 'GHI'], num=(2, 3, 4))
        W.link('Все сбои', 'Сбои', names)
    P = sm.get('страницы')
    if P is not None and len(P):
        W.section('Пострадавшие страницы', 'Топ-10 страниц сайта, на которых люди получили ошибку: что с ними происходило и откуда на них приходят.')
        rows = [[r['адрес'], int(r['Люди']), int(r['Поисковики']), r['статус'], r['источник']] for _, r in P.iterrows()]
        W.table(['Страница', 'Люди', 'Поисковики', 'Статус', 'Источники'], rows, ['BC', 'D', 'E', 'FG', 'HI'], num=(1, 2), wrap=0.95)
        W.link('Все пострадавшие страницы', 'Пострадавшие страницы', names)
    G = sm.get('разделы')
    if G is not None and len(G):
        W.section('Ошибки по разделам', 'Где на сайте больше всего ошибок у людей, своих и поисковиков. Зонды сканеров не учитываются.')
        rows = [[r['раздел'], int(r['адресов']), int(r['Люди']), int(r['Поисковики']), int(r['Свои'])] for _, r in G.head(10).iterrows()]
        W.table(['Раздел', 'Страниц', 'Люди', 'Поисковики', 'Свои'], rows, ['BC', 'D', 'E', 'F', 'G'], num=(1, 2, 3, 4))
    Fe = res.get('files_errors') or []
    if Fe:
        W.section('Файлы с ошибками', 'Файлы, которые запрашивают страницы сайта, реклама, фиды и другие сайты, а сервер их не отдаёт.')
        fg = pd.DataFrame(Fe).groupby('группа').agg(файлов=('файлов', 'sum'), запросов=('запросов', 'sum'), примеры=('адрес', lambda s: list(s)[:2])).sort_values('запросов', ascending=False)
        rows = [[g, int(r['файлов']), int(r['запросов']), '\n'.join(map(str, r['примеры']))] for g, r in fg.iterrows()]
        W.table(['Группа', 'Файлов', 'Запросов', 'Например'], rows, ['B', 'C', 'D', 'EFGHI'], num=(1, 2), wrap=0.95)
        if res.get('files_optional'):
            W.note('Можно добавить: ' + ', '.join(res['files_optional'][:6]) + (' и др.' if len(res['files_optional']) > 6 else '') +
                   ' — необязательные файлы для роботов, нейросетей и устройств. Их нет, и это не ошибка: рекомендация.')
        W.link('Каждый файл', 'Файлы с ошибками', names)
    BI = E.get('битые_внутренние')
    if BI is not None and len(BI):
        W.section('Битые внутренние', 'Ссылки на страницах сайта, которые ведут на несуществующие или неработающие адреса.')
        rows = [[r['откуда'], r['куда'], int(r['переходов']), int(r['людей'])] for _, r in BI.head(5).iterrows()]
        W.table(['Где стоит ссылка', 'Куда ведёт', 'Переходов', 'Люди'], rows, ['BC', 'DEF', 'G', 'H'], num=(2, 3), wrap=0.95)
        W.link('Все внутренние', 'Битые внутренние', names)
    BX = E.get('битые_внешние')
    if BX is not None and len(BX):
        W.section('Битые внешние', 'Ссылки с рекламы, поиска и других сайтов на несуществующие страницы.')
        rows = [[r['вид'], r['откуда'], r['куда'], int(r['переходов']), int(r['людей'])] for _, r in BX.head(5).iterrows()]
        W.table(['Откуда', 'Сайт', 'Куда ведёт', 'Переходов', 'Люди'], rows, ['B', 'C', 'DEF', 'G', 'H'], num=(3, 4), wrap=0.95)
        W.link('Все внешние', 'Битые внешние', names)
    BJ = S.get('Битые адреса из скриптов')
    if BJ is not None and len(BJ):
        W.section('Битые из скриптов', 'Адреса, которые скрипты страниц собрали с ошибкой.')
        rows = [[r['Адрес'], int(r['Запросов со страниц сайта']), r['Страница-источник']] for _, r in BJ.head(5).iterrows()]
        W.table(['Адрес', 'Запросов', 'Страница'], rows, ['BCD', 'E', 'FGHI'], num=(1,))
        W.link('Все битые из скриптов', 'Битые из скриптов', names)
    SE = S.get('Ошибки у поисковиков')
    if SE is not None and len(SE):
        W.section('Поисковики — ошибки', 'Страницы, которые поисковые роботы получают с ошибкой, — они выпадают из поиска.')
        g = SE.groupby('робот').agg(типов=('шаблон', 'nunique'), запросов=('запросов', 'sum'), ошибок=('ошибок', 'sum')).sort_values('ошибок', ascending=False).reset_index()
        W.table(['Робот', 'Типов страниц', 'Запросов', 'Ошибок'], [[r['робот'], int(r['типов']), int(r['запросов']), int(r['ошибок'])] for _, r in g.iterrows()], ['B', 'C', 'D', 'E'], num=(1, 2, 3))
        W.link('Какие страницы', 'Поисковики — ошибки', names)
    AD = S.get('Реклама: посадочные с ошибками')
    if AD is not None and len(AD):
        W.section('Ошибки с рекламы', 'Рекламные переходы, которые привели на неработающую страницу или на страницу, которую человек не дождался.')
        rows = [[r['entry'], int(r['entry_status']), int(r['кликов'])] for _, r in AD.head(5).iterrows()]
        W.table(['Посадочная', 'Код', 'Кликов'], rows, ['BCD', 'E', 'F'], num=(2,), center=(1,))
        W.link('Все посадочные', 'Ошибки с рекламы', names)
    EL = S.get('Error-лог')
    if EL is not None and len(EL):
        W.section('Error-лог', 'Ошибки из журнала сервера: что они значат. Какие запросы их вызвали — на полном листе.')
        rows = [[r['тип'], ERRLOG_MEANING.get(r['тип'], ('', False))[0], int(r['сообщений']), _d(r['первый']), _d(r['последний'])] for _, r in EL.iterrows()]
        W.table(['Тип', 'Что значит', 'Сообщений', 'Первый', 'Последний'], rows, ['B', 'CDE', 'F', 'G', 'H'], num=(2,), center=(3, 4), wrap=0.95)
        W.link('Какие запросы вызывали', 'Error-лог', names)
    ws.page_setup.orientation = 'portrait'; ws.page_setup.fitToWidth = 1; ws.page_setup.fitToHeight = 0
    ws.sheet_properties.pageSetUpPr.fitToPage = True
    return ws


def build(wb, res, S, site):
    E = res.get('errors') or {}
    T, Sr = E.get('коды'), E.get('источники')
    if 'Статистика' not in wb.sheetnames: wb.create_sheet('Статистика')
    def kpi(body):
        h = body['5xx|Люди'] + body['4xx|Люди']
        return [('Ошибок у людей в день', int(round(h[body['_полный']].mean())) if body['_полный'].any() else int(round(h.mean()))),
                ('Больше всего', _day(body.loc[h.idxmax(), 'день']) if len(body) else ''), ('5xx у людей', int(body['5xx|Люди'].sum()))]
    journal_sheet(wb, 'Статистика', E.get('журнал'), 'Ошибки по дням и тем, кто их получил', kpi,
                  [('Сводка ошибок', 'Обзор'), ('Пострадавшие страницы', 'Пострадавшие страницы')],
                  ['4xx — без 499: он показан отдельно, это посетитель, который не дождался ответа. Поисковики — только подлинные роботы поисковых систем.',
                   'Время — какая часть суток попала в лог; неполные дни — серым курсивом, в среднее не входят. Выходные — на сером.'], kpi_col='4xx|Люди')
    for fam, _ in FAMILIES:
        if fam not in wb.sheetnames: wb.create_sheet(fam)
        if code_tab(wb, T, Sr, fam) is None: del wb[fam]
    victims(wb, E)
    if res.get('files_errors'):
        service_files(wb, dict(res, files=res['files_errors']), 'Файлы с ошибками', title='Файлы с ошибками',
                      note='Файлы, которые запрашивают страницы сайта, реклама, фиды и другие сайты, а сервер их не отдаёт',
                      links=[('Сводка ошибок', 'Обзор'), ('Все адреса с 404', '404')], errors_mode=True)
        if res.get('files_optional'):
            notes(wb['Файлы с ошибками'], ['Можно добавить (необязательные, не ошибка): ' + ', '.join(res['files_optional']) + '.'])
    links_sheets(wb, E)
    full_sheets(wb, S)
    overview(wb, res, S, site)
    byname = {w.title: w for w in wb._sheets}
    head_ = [byname[n_] for n_ in ORDER if n_ in byname]
    wb._sheets = head_ + [w for w in wb._sheets if w not in head_]
