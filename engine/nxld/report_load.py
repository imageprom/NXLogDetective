        for _, r in Z[Z['внутренних_без_входа'] > 0].iterrows():
            alarms.append([r['раздел'], 'страницы раздела открываются без входа', f"{int(r['внутренних_без_входа'])} ответов: {r['страницы_без_входа']}"])
